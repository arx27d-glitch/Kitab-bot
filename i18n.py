# Telegram language_code -> our code (used when the user has not chosen a language yet)
_ALIASES = {"iw": "he", "in": "id", "ua": "uk", "pt-br": "pt", "pt-pt": "pt", "zh-hans": "zh",
            "zh-hant": "zh", "zh-cn": "zh", "zh-tw": "zh", "nb": "sv", "no": "sv"}


def detect_lang(code) -> str:
    code = (code or "").lower().replace("_", "-")
    if code in _ALIASES:
        return _ALIASES[code]
    short = code.split("-")[0]
    short = _ALIASES.get(short, short)
    return short if short in LANGS else "en"


